export const translations: Record<Locale, Record<MessageKey, string>> = {
  en,
  lt,
}

export function isLocale(value: string | null | undefined): value is Locale {
  return value === 'en' || value === 'lt'
}

export function detectLocale(): Locale {
  if (typeof window === 'undefined') {
    return 'en'
  }
  const saved = window.localStorage.getItem('platform_locale')
  if (isLocale(saved)) {
    return saved
  }
  return window.navigator.language.toLowerCase().startsWith('lt') ? 'lt' : 'en'
}

export function localeTag(locale: Locale): string {
  return locale === 'lt' ? 'lt-LT' : 'en-GB'
}

export function translate(
  locale: Locale,
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  let text = translations[locale][key] ?? translations.en[key] ?? key
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}
